package testgen

import (
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"testing"
)

// writePkg 在暫存目錄寫入一組檔案並回傳目錄
func writePkg(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// added 對目錄跑 GenerateForDir，回傳所有新增的 Test 名稱
func added(t *testing.T, dir string) []string {
	t.Helper()
	reports, err := GenerateForDir(dir, DefaultOptions())
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, r := range reports {
		out = append(out, r.Added...)
	}
	slices.Sort(out)
	return out
}

// TestGenericReceiver 迴歸測試：泛型 receiver 產生合法的 Test 名稱，產出的檔案可解析。
// 歷史 bug：*List[T] 落到 %T，產生 func Test*ast.IndexExpr_Push，整個套件的測試編不過
func TestGenericReceiver(t *testing.T) {
	dir := writePkg(t, map[string]string{"list.go": `package p

type List[T any] struct{ items []T }

func (l *List[T]) Push(v T) { l.items = append(l.items, v) }

type Pair[K comparable, V any] struct{}

func (Pair[K, V]) Key() {}
`})
	if got, want := added(t, dir), []string{"TestList_Push", "TestPair_Key"}; !slices.Equal(got, want) {
		t.Errorf("added %v, want %v", got, want)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, "list_test.go"), nil, 0); err != nil {
		t.Errorf("generated test file does not parse: %v", err)
	}
}

// TestExistingTestInOtherFile 迴歸測試：同名測試寫在同套件其他測試檔（含 package x_test）時不再重複產生。
// 歷史 bug：只看 add_test.go，math_test.go 已有 TestAdd 仍補一個，TestAdd redeclared
func TestExistingTestInOtherFile(t *testing.T) {
	dir := writePkg(t, map[string]string{
		"add.go":       "package p\n\nfunc Add(a, b int) int { return a + b }\n\nfunc Sub(a, b int) int { return a - b }\n",
		"math_test.go": "package p\n\nimport \"testing\"\n\nfunc TestAdd(t *testing.T) {}\n",
		"ext_test.go":  "package p_test\n\nimport \"testing\"\n\nfunc TestSub(t *testing.T) {}\n",
	})
	if got := added(t, dir); len(got) != 0 {
		t.Errorf("added %v, want none (TestAdd / TestSub already exist in other test files)", got)
	}
}

// TestRenamedTestCounts 迴歸測試：Test<名稱> 之後接大寫、底線或數字的測試算已覆蓋；
// 接小寫的不算（TestAddress 不是 Add 的測試）；同時符合多個候選時歸給名稱最長者。
// 歷史 bug：只認完全同名，TestAddWorks 旁仍補 TestAdd 空殼
func TestRenamedTestCounts(t *testing.T) {
	dir := writePkg(t, map[string]string{
		"svc.go": `package p

func Add(a, b int) int    { return a + b }
func Parse(s string) int  { return 0 }
func Get() int            { return 0 }
func GetUser() int        { return 0 }
func Address() string     { return "" }
`,
		"svc_test.go": `package p

import "testing"

func TestAddWorks(t *testing.T)      {}
func TestParse_Empty(t *testing.T)   {}
func TestGetUserFound(t *testing.T)  {}
func TestAddress2(t *testing.T)      {}
`,
	})
	// TestAddWorks → Add、TestParse_Empty → Parse、TestGetUserFound → GetUser（不是 Get）、
	// TestAddress2 → Address；Get 沒有測試
	if got, want := added(t, dir), []string{"TestGet"}; !slices.Equal(got, want) {
		t.Errorf("added %v, want %v", got, want)
	}
}

// TestSkipsGeneratedFiles 迴歸測試：自動產生的檔案不補測試。
// 歷史 bug：.pb.go 的每個 getter 都得到一個空殼
func TestSkipsGeneratedFiles(t *testing.T) {
	dir := writePkg(t, map[string]string{
		"msg.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n\ntype Msg struct{}\n\nfunc (x *Msg) GetName() string { return \"\" }\n",
	})
	if got := added(t, dir); len(got) != 0 {
		t.Errorf("added %v for a generated file", got)
	}
	if _, err := os.Stat(filepath.Join(dir, "msg.pb_test.go")); err == nil {
		t.Error("test file created for a generated file")
	}
}
