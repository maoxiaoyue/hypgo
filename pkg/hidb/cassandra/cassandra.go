// ErrNotConnected is returned by every query path when the instance has no
// session: built with NewWithoutConnect and not yet connected, or closed.
// Previously most builders dereferenced the nil session and panicked.
var ErrNotConnected = errors.New("cassandra: session not connected")

// ErrNotApplied is returned by Exec (and Save / UpdateModel) when a
// lightweight transaction (IF NOT EXISTS / IF EXISTS / IF ...) was not
// applied. Previously the [applied] column was never read, so a rejected
// conditional write reported success. Use ExecCAS to also read the existing row.
var ErrNotApplied = errors.New("cassandra: lightweight transaction not applied")

// TLSConfig holds optional TLS settings for the CQL connection.
type TLSConfig struct {
	Enabled            bool   `mapstructure:"enabled" yaml:"enabled"`
	CertFile           string `mapstructure:"cert_file" yaml:"cert_file"`
	KeyFile            string `mapstructure:"key_file" yaml:"key_file"`
	CaFile             string `mapstructure:"ca_file" yaml:"ca_file"`
	ServerName         string `mapstructure:"server_name" yaml:"server_name"`
	InsecureSkipVerify bool   `mapstructure:"insecure_skip_verify" yaml:"insecure_skip_verify"`
	// Config, when set, overrides CertFile/KeyFile/CaFile and is passed
	// directly to gocql via SslOptions.Config.
	Config *tls.Config `mapstructure:"-" yaml:"-"`
}

// Config Cassandra 配置
type Config struct {
	Hosts            []string      `mapstructure:"hosts" yaml:"hosts"`
	Keyspace         string        `mapstructure:"keyspace" yaml:"keyspace"`
	Consistency      string        `mapstructure:"consistency" yaml:"consistency"` // "one", "quorum", "all", "local_quorum" 等
	Port             int           `mapstructure:"port" yaml:"port"`               // 預設 9042
	Username         string        `mapstructure:"username" yaml:"username"`
	Password         string        `mapstructure:"password" yaml:"password"`
	ConnectTimeout   time.Duration `mapstructure:"connect_timeout" yaml:"connect_timeout"` // 預設 5s
	Timeout          time.Duration `mapstructure:"timeout" yaml:"timeout"`                 // 預設 10s
	NumConns         int           `mapstructure:"num_conns" yaml:"num_conns"`             // 每個主機的連接數
	MaxPreparedStmts int           `mapstructure:"max_prepared_stmts" yaml:"max_prepared_stmts"`
	ProtoVersion     int           `mapstructure:"proto_version" yaml:"proto_version"` // 預設 4

	// Retry / Reconnect — 預設 production-friendly。設為負值關閉。
	NumRetries        int           `mapstructure:"num_retries" yaml:"num_retries"`               // 預設 3
	RetryMinDelay     time.Duration `mapstructure:"retry_min_delay" yaml:"retry_min_delay"`       // 預設 100ms
	RetryMaxDelay     time.Duration `mapstructure:"retry_max_delay" yaml:"retry_max_delay"`       // 預設 10s
	ReconnectInterval time.Duration `mapstructure:"reconnect_interval" yaml:"reconnect_interval"` // 預設 1s
	ReconnectMax      int           `mapstructure:"reconnect_max" yaml:"reconnect_max"`           // 預設 10

	// TLS 連線設定（dev 環境留空即可）
	TLS TLSConfig `mapstructure:"tls" yaml:"tls"`

	// QueryObserver 注入點，提供 latency / error / pool metrics（gocql QueryObserver）。
	// 注意：此欄位不從 YAML 解析，僅供程式碼直接設定。
	QueryObserver gocql.QueryObserver `mapstructure:"-" yaml:"-"`

	// StrictConsistency=true 時，Consistency 字串無法解析會直接回 error。
	// 預設 false → 無法解析時 fallback 為 LocalOne（並非 Quorum，更利於單節點 dev）。
	StrictConsistency bool `mapstructure:"strict_consistency" yaml:"strict_consistency"`
}

// CassandraDB Cassandra 數據庫管理器
type CassandraDB struct {
	cluster *gocql.ClusterConfig
	session *gocql.Session
	config  Config

	mu     sync.Mutex
	closed bool
}

// New 創建 Cassandra 實例並建立連接。
//
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
// @ai:purpose 一步完成 cluster 設定 + session 建立，呼叫端拿到即可使用
// @ai:input Config（必填 Hosts；其餘有預設值）
// @ai:output 已連線的 *CassandraDB 或設定 / 連線錯誤
// @ai:sideeffect 建立 gocql Session（TCP 連線到 Cassandra cluster）
func New(cfg Config) (*CassandraDB, error) {
	c := &CassandraDB{
		config: cfg,
	}

	if err := c.init(); err != nil {
		return nil, err
	}

	if err := c.Connect(); err != nil {
		return nil, err
	}

	return c, nil
}

// NewWithoutConnect 創建 Cassandra 實例但不立即連接。
//
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
// @ai:purpose 用於需要延遲連線的情境（測試 / DDL 預組）
// @ai:input Config
// @ai:output *CassandraDB（未連線）或設定錯誤
// @ai:sideeffect none
func NewWithoutConnect(cfg Config) (*CassandraDB, error) {
	c := &CassandraDB{
		config: cfg,
	}

	if err := c.init(); err != nil {
		return nil, err
	}

	return c, nil
}

// init 初始化 cluster 配置。
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
func (c *CassandraDB) init() error {
	if len(c.config.Hosts) == 0 {
		return fmt.Errorf("cassandra: at least one host is required")
	}

	cluster := gocql.NewCluster(c.config.Hosts...)

	// Keyspace
	if c.config.Keyspace != "" {
		cluster.Keyspace = c.config.Keyspace
	}

	// Consistency — 嚴格模式下拼錯直接 error，非嚴格 fallback 至 LocalOne
	cl, err := parseConsistencyStrict(c.config.Consistency)
	if err != nil {
		if c.config.StrictConsistency {
			return err
		}
		cl = gocql.LocalOne
	}
	cluster.Consistency = cl

	// Port
	if c.config.Port > 0 {
		cluster.Port = c.config.Port
	}

	// 認證
	if c.config.Username != "" {
		cluster.Authenticator = gocql.PasswordAuthenticator{
			Username: c.config.Username,
			Password: c.config.Password,
		}
	}

	// 超時設置
	if c.config.ConnectTimeout > 0 {
		cluster.ConnectTimeout = c.config.ConnectTimeout
	} else {
		cluster.ConnectTimeout = 5 * time.Second
	}

	if c.config.Timeout > 0 {
		cluster.Timeout = c.config.Timeout
	} else {
		cluster.Timeout = 10 * time.Second
	}

	// 連接池
	if c.config.NumConns > 0 {
		cluster.NumConns = c.config.NumConns
	}

	if c.config.MaxPreparedStmts > 0 {
		cluster.MaxPreparedStmts = c.config.MaxPreparedStmts
	}

	// 協議版本
	if c.config.ProtoVersion > 0 {
		cluster.ProtoVersion = c.config.ProtoVersion
	} else {
		cluster.ProtoVersion = 4
	}

	// Retry policy（NumRetries < 0 表示停用）
	if c.config.NumRetries >= 0 {
		retries := c.config.NumRetries
		if retries == 0 {
			retries = 3
		}
		minD := c.config.RetryMinDelay
		if minD <= 0 {
			minD = 100 * time.Millisecond
		}
		maxD := c.config.RetryMaxDelay
		if maxD <= 0 {
			maxD = 10 * time.Second
		}
		cluster.RetryPolicy = &gocql.ExponentialBackoffRetryPolicy{
			NumRetries: retries,
			Min:        minD,
			Max:        maxD,
		}
	}

	// Reconnection policy
	// ReconnectMax < 0 → 明確停用（覆寫 gocql 預設為 nil）
	// ReconnectMax = 0 → 使用 hidb 預設 (10 retries, 1s interval)
	// ReconnectMax > 0 → 使用使用者指定值
	if c.config.ReconnectMax < 0 {
		cluster.ReconnectionPolicy = nil
	} else {
		maxR := c.config.ReconnectMax
		if maxR == 0 {
			maxR = 10
		}
		intv := c.config.ReconnectInterval
		if intv <= 0 {
			intv = 1 * time.Second
		}
		cluster.ReconnectionPolicy = &gocql.ConstantReconnectionPolicy{
			MaxRetries: maxR,
			Interval:   intv,
		}
	}

	// TLS
	if c.config.TLS.Enabled {
		ssl, err := buildSslOptions(c.config.TLS)
		if err != nil {
			return fmt.Errorf("cassandra: tls config: %w", err)
		}
		cluster.SslOpts = ssl
	}

	// QueryObserver
	if c.config.QueryObserver != nil {
		cluster.QueryObserver = c.config.QueryObserver
	}

	c.cluster = cluster
	return nil
}

// buildSslOptions translates TLSConfig into gocql.SslOptions.
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
//
// gocql only honours EnableHostVerification when SslOptions.Config is nil;
// with a Config it verifies unless Config.InsecureSkipVerify is set (and
// always verifies when EnableHostVerification is true). So the flag is
// carried into every Config built here, and a caller-supplied Config keeps
// its own InsecureSkipVerify. Previously server_name dropped
// insecure_skip_verify and a supplied Config with InsecureSkipVerify was
// forced back to verifying.
func buildSslOptions(t TLSConfig) (*gocql.SslOptions, error) {
	opts := &gocql.SslOptions{
		EnableHostVerification: !t.InsecureSkipVerify,
	}
	if t.Config != nil {
		opts.Config = t.Config
		opts.EnableHostVerification = !t.Config.InsecureSkipVerify
		return opts, nil
	}
	if t.CertFile != "" && t.KeyFile == "" {
		return nil, fmt.Errorf("cert_file set but key_file is empty")
	}
	opts.CertPath = t.CertFile
	opts.KeyPath = t.KeyFile
	opts.CaPath = t.CaFile
	if t.ServerName != "" {
		opts.Config = &tls.Config{ServerName: t.ServerName, InsecureSkipVerify: t.InsecureSkipVerify}
	}
	return opts, nil
}

// Connect 建立 Cassandra 連接（idempotent）。
//
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
// @ai:purpose 安全建立或重建 session — 已連線時 no-op，重連時關閉舊 session 不洩漏
// @ai:input none
// @ai:output 連線錯誤或 nil
// @ai:sideeffect 建立 gocql.Session；重連時關閉舊 session
func (c *CassandraDB) Connect() error {
	c.mu.Lock()
	defer c.mu.Unlock()

	if c.closed {
		return fmt.Errorf("cassandra: cannot connect on closed instance")
	}
	if c.cluster == nil {
		return fmt.Errorf("cassandra: cluster config not initialized")
	}
	// 已有有效 session 則 no-op；舊 session 已關閉則先丟棄
	if c.session != nil {
		if !c.session.Closed() {
			return nil
		}
		c.session.Close()
		c.session = nil
	}

	session, err := c.cluster.CreateSession()
	if err != nil {
		return fmt.Errorf("cassandra: failed to create session: %w", err)
	}
	c.session = session
	return nil
}

// sess returns the current session and counts one Cassandra operation for
// pkg/resource. Every query path in this package goes through it: previously
// most of them read c.session directly — without the lock (a data race with
// Close / Connect), without counting (contract reports showed Cassandra x0),
// and panicking on a nil session.
func (c *CassandraDB) sess() (*gocql.Session, error) {
	c.mu.Lock()
	s := c.session
	c.mu.Unlock()
	if s == nil {
		return nil, ErrNotConnected
	}
	resource.MarkCassandra()
	return s, nil
}

// newQuery builds a query bound to ctx with an optional consistency override.
func (c *CassandraDB) newQuery(ctx context.Context, stmt string, args []interface{}, cl *gocql.Consistency) (*gocql.Query, error) {
	s, err := c.sess()
	if err != nil {
		return nil, err
	}
	q := s.Query(stmt, args...).WithContext(ctx)
	if cl != nil {
		q = q.Consistency(*cl)
	}
	return q, nil
}

// newExec runs a bound statement that returns no rows.
func (c *CassandraDB) newExec(ctx context.Context, stmt string, args ...interface{}) error {
	q, err := c.newQuery(ctx, stmt, args, nil)
	if err != nil {
		return err
	}
	return q.Exec()
}

// execQuery runs q; when lwt is set it reads the [applied] column and returns
// ErrNotApplied if the condition did not hold.
func execQuery(q *gocql.Query, lwt bool) error {
	if !lwt {
		return q.Exec()
	}
	applied, err := q.MapScanCAS(map[string]interface{}{})
	if err != nil {
		return err
	}
	if !applied {
		return ErrNotApplied
	}
	return nil
}

// Session 獲取 gocql.Session（用戶直接操作 CQL）；未連線或已關閉時回傳 nil
func (c *CassandraDB) Session() *gocql.Session {
	resource.MarkCassandra()
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.session
}

// Close 關閉 Cassandra 連接（thread-safe，可重複呼叫）。
//
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
// @ai:purpose 安全關閉 session — 多 goroutine 同時 / 重複呼叫不會 panic 或 double-close
// @ai:input none
// @ai:output nil（保留介面相容）
// @ai:sideeffect 關閉底層 gocql Session
func (c *CassandraDB) Close() error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.closed {
		return nil
	}
	if c.session != nil {
		c.session.Close()
		c.session = nil
	}
	c.closed = true
	return nil
}

// Ping 健康檢查。
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
func (c *CassandraDB) Ping(ctx context.Context) error {
	sess, err := c.sess()
	if err != nil {
		return err
	}

	iter := sess.Query("SELECT now() FROM system.local").WithContext(ctx).Iter()
	if err := iter.Close(); err != nil {
		return fmt.Errorf("cassandra: ping failed: %w", err)
	}
	return nil
}

// IsConnected 檢查是否已連接。
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
func (c *CassandraDB) IsConnected() bool {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.session == nil {
		return false
	}
	return !c.session.Closed()
}

// ===== Cassandra 特殊功能 =====

// Exec executes a single CQL statement (DDL or DML) without returning rows.
// The statement may be terminated with a trailing ';', which is stripped
// before dispatch. For multi-statement scripts or parameterised CQL, use
// ExecScript or Session().Query respectively.
func (c *CassandraDB) Exec(ctx context.Context, stmt string) error {
	stmt = strings.TrimSpace(stmt)
	stmt = strings.TrimRight(stmt, ";")
	stmt = strings.TrimRight(stmt, " \t\r\n")
	if stmt == "" {
		return nil
	}
	q, err := c.newQuery(ctx, stmt, nil, nil)
	if err != nil {
		return err
	}
	return q.Exec()
}

// ExecScript executes a multi-statement CQL script, ignoring empty segments.
// Bind args are not supported; use separate Exec calls for parameterised CQL.
func (c *CassandraDB) ExecScript(ctx context.Context, script string) error {
	for i, p := range splitStatements(script) {
		q, err := c.newQuery(ctx, p, nil, nil)
		if err != nil {
			return err
		}
		if err := q.Exec(); err != nil {
			return fmt.Errorf("cassandra: stmt %d failed: %w", i+1, err)
		}
	}
	return nil
}

// splitStatements splits a CQL script on top-level semicolons, ignoring those
// inside '...' literals, "..." identifiers, $$-delimited function bodies and
// comments (-- and // to end of line, /* ... */). Comments are dropped.
// Previously comments were not recognised: an apostrophe in "-- don't" opened
// a literal and swallowed every later semicolon.
func splitStatements(src string) []string {
	var out []string
	var cur strings.Builder
	flush := func() {
		if s := strings.TrimSpace(cur.String()); s != "" {
			out = append(out, s)
		}
		cur.Reset()
	}
	for i := 0; i < len(src); i++ {
		ch := src[i]
		next := byte(0)
		if i+1 < len(src) {
			next = src[i+1]
		}
		switch {
		case ch == '\'' || ch == '"':
			// copy the literal / quoted identifier verbatim ('' and "" are escapes)
			j := i + 1
			for j < len(src) {
				if src[j] == ch {
					if j+1 < len(src) && src[j+1] == ch {
						j += 2
						continue
					}
					break
				}
				j++
			}
			end := min(j+1, len(src))
			cur.WriteString(src[i:end])
			i = end - 1
		case ch == '$' && next == '$':
			end := strings.Index(src[i+2:], "$$")
			if end < 0 {
				cur.WriteString(src[i:])
				i = len(src)
				break
			}
			cur.WriteString(src[i : i+2+end+2])
			i += 2 + end + 1
		case (ch == '-' && next == '-') || (ch == '/' && next == '/'):
			end := strings.IndexByte(src[i:], '\n')
			if end < 0 {
				i = len(src)
				break
			}
			cur.WriteByte('\n')
			i += end
		case ch == '/' && next == '*':
			end := strings.Index(src[i+2:], "*/")
			if end < 0 {
				i = len(src)
				break
			}
			cur.WriteByte(' ')
			i += 2 + end + 1
		case ch == ';':
			flush()
		default:
			cur.WriteByte(ch)
		}
	}
	flush()
	return out
}

// KeyspaceName returns the current session keyspace (from config).
func (c *CassandraDB) KeyspaceName() string {
	return c.config.Keyspace
}

// parseConsistencyStrict 嚴格解析；未知 / 拼錯回 error 而非 silent fallback。
// 空字串視為「未指定」，回傳 LocalOne 與 nil error。
//
// @ai:generated by=claude-sonnet-4-6 date=2026-04-29
// @ai:purpose 阻止「設定拼錯但悄悄變 Quorum 害 dev 卡死」這個歷史 bug
// @ai:input consistency 字串
// @ai:output gocql.Consistency 或 error（不認得的值）
// @ai:sideeffect none
func parseConsistencyStrict(s string) (gocql.Consistency, error) {
	norm := strings.ReplaceAll(strings.TrimSpace(strings.ToLower(s)), "-", "_")
	switch norm {
	case "":
		return gocql.LocalOne, nil
	case "any":
		return gocql.Any, nil
	case "one":
		return gocql.One, nil
	case "two":
		return gocql.Two, nil
	case "three":
		return gocql.Three, nil
	case "quorum":
		return gocql.Quorum, nil
	case "all":
		return gocql.All, nil
	case "local_quorum", "localquorum":
		return gocql.LocalQuorum, nil
	case "each_quorum", "eachquorum":
		return gocql.EachQuorum, nil
	case "local_one", "localone":
		return gocql.LocalOne, nil
	default:
		return 0, fmt.Errorf("cassandra: unknown consistency level %q (valid: any/one/two/three/quorum/all/local_quorum/each_quorum/local_one)", s)
	}
}
