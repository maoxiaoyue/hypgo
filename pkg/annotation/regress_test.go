// TestFixThinkSkipsUnsafeBraceLines 迴歸測試（A3）：`{` 同行還有程式碼的函式不插入 @ai:think，重跑也不重複插入。
// 歷史 bug：一律插在 `{` 的下一行——單行函式體的 think 行落到函式外（變成下一個函式的 doc），
// `{` 同行開始的多行 raw string 則被插進字串內容；每次重跑都再插一次。
func TestFixThinkSkipsUnsafeBraceLines(t *testing.T) {
	path := writeTempGo(t, "package p\n\n// @ai:generated by=x date=2026-01-01\nfunc One() { println(\"one\") }\n\n// Next 是下一個函式。\n// @ai:generated by=x date=2026-01-01\nfunc Next() {\n\tprintln(\"next\")\n}\n\n// @ai:generated by=x date=2026-01-01\nfunc Raw() string { return `a\nb` }\n")
	run := func() {
		report, err := CheckThink(path)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := FixThinkFile(context.Background(), path, report, &heuristicThinkSuggester{}); err != nil {
			t.Fatal(err)
		}
	}
	run()
	if outside := thinkOutsideBodies(t, path); len(outside) > 0 {
		t.Fatalf("@ai:think inserted outside func bodies: %q\n%s", outside, readFileString(t, path))
	}
	out := readFileString(t, path)
	if !strings.Contains(out, "a\nb`") {
		t.Errorf("raw string content changed:\n%s", out)
	}
	if strings.Count(out, "@ai:think") != 1 {
		t.Errorf("want exactly one @ai:think (in Next), got:\n%s", out)
	}
	run()
	if again := readFileString(t, path); again != out {
		t.Errorf("rerun changed the file again:\n%s", again)
	}
}

