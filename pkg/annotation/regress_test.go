// TestLLMSendsResolvedAPIKey 迴歸測試（A6）：送出的 API key 是展開 ${ENV} 之後的值。
// 歷史 bug：直接送 cfg.API.APIKey，`${OPENAI_API_KEY}` 被原樣送出 → 401 → 靜默退回 heuristic。
func TestLLMSendsResolvedAPIKey(t *testing.T) {
	t.Setenv("HYP_REGRESS_KEY", "sk-real")
	var got []string
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if strings.HasSuffix(r.URL.Path, "/messages") {
			got = append(got, r.Header.Get("x-api-key"))
			io.WriteString(w, `{"content":[{"type":"text","text":"{}"}]}`)
			return
		}
		got = append(got, r.Header.Get("Authorization"))
		io.WriteString(w, `{"choices":[{"message":{"role":"assistant","content":"{}"}}]}`)
	}))
	defer srv.Close()

	for _, provider := range []string{"openai", "anthropic"} {
		s, err := NewLLMSuggester(&config.LLMConfig{Mode: config.LLMModeAPI, API: config.APIConfig{
			Provider: provider, BaseURL: srv.URL, APIKey: "${HYP_REGRESS_KEY}", Model: "m",
		}})
		if err != nil {
			t.Fatal(err)
		}
		if _, err := s.Suggest(context.Background(), SuggestRequest{Kind: "func", Name: "F"}); err != nil {
			t.Fatalf("%s: %v", provider, err)
		}
	}
	want := []string{"Bearer sk-real", "sk-real"}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Errorf("sent keys = %q, want %q", got, want)
	}
}

