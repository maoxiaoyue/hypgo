func regressResponse(body string) *http.Response {
	return &http.Response{
		StatusCode: http.StatusOK,
		Header:     http.Header{"Content-Type": []string{"application/json"}},
		Body:       io.NopCloser(strings.NewReader(body)),
	}
}

func readFileString(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// thinkOutsideBodies 回傳不在任何函式體內的 @ai:think 註解（應為空）；檔案無法解析時直接失敗。
func thinkOutsideBodies(t *testing.T, path string) []string {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		t.Fatalf("file no longer parses: %v\n%s", err, readFileString(t, path))
	}
	var outside []string
	for _, cg := range f.Comments {
		for _, c := range cg.List {
			if !strings.Contains(c.Text, "@ai:think") {
				continue
			}
			in := false
			for _, d := range f.Decls {
				if fd, ok := d.(*ast.FuncDecl); ok && fd.Body != nil &&
					c.Pos() > fd.Body.Lbrace && c.Pos() < fd.Body.Rbrace {
					in = true
				}
			}
			if !in {
				outside = append(outside, c.Text)
			}
		}
	}
	return outside
}

