// 歷史 bug：Anthropic 固定送 512、Ollama 完全不送，設定的 max_tokens 無效。
func TestLLMHonorsMaxTokens(t *testing.T) {
	var bodies []map[string]any
	capture := regressRoundTrip(func(r *http.Request) (*http.Response, error) {
		var m map[string]any
		_ = json.NewDecoder(r.Body).Decode(&m)
		bodies = append(bodies, m)
		if strings.HasSuffix(r.URL.Path, "/messages") {
			return regressResponse(`{"content":[{"type":"text","text":"{}"}]}`), nil
		}
		return regressResponse(`{"response":"{}"}`), nil
	})

	a, err := NewLLMSuggester(&config.LLMConfig{Mode: config.LLMModeAPI, API: config.APIConfig{
		Provider: "anthropic", BaseURL: "http://x", APIKey: "k", Model: "m", MaxTokens: 100,
	}})
	if err != nil {
		t.Fatal(err)
	}
	a.client = &http.Client{Transport: capture}
	if _, err := a.callAPI(context.Background(), "p"); err != nil {
		t.Fatal(err)
	}

	o, err := NewLLMSuggester(&config.LLMConfig{Mode: config.LLMModeOllama, Ollama: config.OllamaConfig{
		URL: "http://x", Model: "m", MaxTokens: 77,
	}})
	if err != nil {
		t.Fatal(err)
	}
	o.client = &http.Client{Transport: capture}
	if _, err := o.callOllama(context.Background(), "p"); err != nil {
		t.Fatal(err)
	}

	if len(bodies) != 2 {
		t.Fatalf("captured %d bodies", len(bodies))
	}
	if got := bodies[0]["max_tokens"]; got != float64(100) {
		t.Errorf("anthropic max_tokens = %v, want 100", got)
	}
	opts, _ := bodies[1]["options"].(map[string]any)
	if got := opts["num_predict"]; got != float64(77) {
		t.Errorf("ollama options.num_predict = %v, want 77", got)
	}
}

// TestOllamaResponseIsBounded 迴歸測試（B9）：Ollama 回應有大小上限。
// 歷史 bug：io.ReadAll 無上限讀取回應，異常或惡意伺服器可讓 hyp 吃光記憶體。
func TestOllamaResponseIsBounded(t *testing.T) {
	o, err := NewLLMSuggester(&config.LLMConfig{Mode: config.LLMModeOllama, Ollama: config.OllamaConfig{URL: "http://x", Model: "m"}})
	if err != nil {
		t.Fatal(err)
	}
	huge := `{"response":"` + strings.Repeat("a", 5<<20) + `"}`
	o.client = &http.Client{Transport: regressRoundTrip(func(*http.Request) (*http.Response, error) {
		return regressResponse(huge), nil
	})}
	if out, err := o.callOllama(context.Background(), "p"); err == nil {
		t.Errorf("5MB response accepted (len=%d); want an error", len(out))
	}
}

// TestGitDeclHistoryMatchesExactName 迴歸測試（B9）：git log -L 只追蹤同名函式，不會被前綴相同的函式搶先匹配。
// 歷史 bug：`-L :Get:file` 的 Get 是 regex，先匹配到上方的 `func GetAll`，回傳的是 GetAll 的歷史。
func TestGitDeclHistoryMatchesExactName(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not available")
	}
	repo := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", append([]string{"-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false"}, args...)...)
		cmd.Dir = repo
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	write := func(src string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(repo, "x.go"), []byte(src), 0644); err != nil {
			t.Fatal(err)
		}
	}
	git("init", "-q")
	write("package p\n\nfunc GetAll() {\n}\n")
	git("add", "x.go")
	git("commit", "-q", "-m", "add GetAll")
	write("package p\n\nfunc GetAll() {\n}\n\nfunc Get() {\n}\n")
	git("commit", "-q", "-am", "add Get")
	write("package p\n\nfunc GetAll() {\n\tprintln()\n}\n\nfunc Get() {\n}\n")
	git("commit", "-q", "-am", "change GetAll")

	t.Chdir(repo)
	gc := GatherGitContext("x.go", "Get", "func", 10)
	if gc == nil {
		t.Fatal("no git context")
	}
	var subjects []string
	for _, c := range gc.DeclCommits {
		subjects = append(subjects, c.Subject)
	}
	if got := strings.Join(subjects, "|"); got != "add Get" {
		t.Errorf("decl commits = %q, want only \"add Get\"", got)
	}
}
