// runChkCommentCmd 以 cobra 執行 `hyp chkcomment <args>`；cobra 旗標值會跨次保留，執行前先還原為預設值。
func runChkCommentCmd(t *testing.T, args ...string) error {
	t.Helper()
	for _, name := range []string{"fix", "unintent", "fixintent", "all", "llm"} {
		f := chkcommentCmd.Flags().Lookup(name)
		_ = f.Value.Set(f.DefValue)
		f.Changed = false
	}
	rootCmd.SetArgs(append([]string{"chkcomment"}, args...))
	return rootCmd.Execute()
}

func writeChkFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}
}

const commentYAMLAllOn = "normal_comment: true\nai_comment: true\nthink_comment: true\n"

// TestChkCommentFixAfterFixIntentUsesFreshLines 迴歸測試（A1）：--fix --fixintent 一起用時，--fix 依插入 think 之後的行號寫入。
// 歷史 bug：--fixintent 插入新行後仍沿用第一次 CheckFile 的結果，--fix 把下一個函式的 doc 插進前一個函式體內，
// 該函式依舊沒有 doc（嚴重時蓋掉 `}`、doc 落進下一個函式體）。
func TestChkCommentFixAfterFixIntentUsesFreshLines(t *testing.T) {
	resp, _ := json.Marshal(map[string]string{"response": `{"doc":"D 說明","intent":"I","special":""}`})
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		_, _ = w.Write(resp)
	}))
	defer srv.Close()

	dir := t.TempDir()
	t.Chdir(dir)
	writeChkFile(t, ".hyp/comment.yaml", commentYAMLAllOn)
	writeChkFile(t, ".hyp/llm.yaml", "mode: ollama\nollama:\n  url: "+srv.URL+"\n  model: m\n")
	writeChkFile(t, "x.go", "package p\n\n// A does a.\n// @ai:generated by=x date=2026-01-01\nfunc A() {\n\tprintln(\"a\")\n}\nfunc B() {\n\tprintln(\"b\")\n}\n")

	_ = runChkCommentCmd(t, "--fix", "--fixintent", "x.go")

	out, _ := os.ReadFile("x.go")
	f, err := parser.ParseFile(token.NewFileSet(), "x.go", out, parser.ParseComments)
	if err != nil {
		t.Fatalf("file broken after fix: %v\n%s", err, out)
	}
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok {
			continue
		}
		// B 的 doc 必須緊貼在 `func B` 上方；A 的函式體內只能有 @ai:think
		if fd.Name.Name == "B" && fd.Doc == nil {
			t.Errorf("func B got no doc comment:\n%s", out)
		}
		for _, cg := range f.Comments {
			if cg.Pos() > fd.Body.Lbrace && cg.End() < fd.Body.Rbrace && !strings.Contains(cg.Text(), "@ai:think") {
				t.Errorf("doc comment landed inside func %s body:\n%s", fd.Name.Name, out)
			}
		}
	}
	if report, err := annotation.CheckFile("x.go"); err != nil || report.Passed != report.Total {
		t.Errorf("blocks still failing after --fix --fixintent (err=%v):\n%s", err, out)
	}
}

// TestChkCommentExitCode 迴歸測試（CMD-B5）：有違規時 exit 非零；--fix 全部補齊後 exit 0。
// 歷史 bug：不論有多少區塊不合格都回傳 nil（exit 0），無法當 CI gate。
func TestChkCommentExitCode(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	writeChkFile(t, ".hyp/comment.yaml", commentYAMLAllOn)
	writeChkFile(t, "x.go", "package p\n\nfunc F() {}\n")

	if err := runChkCommentCmd(t, "x.go"); err == nil {
		t.Error("violations should make chkcomment fail")
	}
	if err := runChkCommentCmd(t, "--fix", "x.go"); err != nil {
		t.Errorf("--fix fixed everything, want success; got %v", err)
	}
}

// TestChkCommentFixIntentHeuristicWhenNoLLM 迴歸測試（CMD-B6）：mode=none 時 --fixintent 改用內建啟發式補 @ai:think。
// 歷史 bug：沒有 LLM 設定時只印警告、什麼都不做，與說明的「LLM or heuristics」不符。
func TestChkCommentFixIntentHeuristicWhenNoLLM(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	writeChkFile(t, ".hyp/comment.yaml", commentYAMLAllOn)
	writeChkFile(t, "x.go", "// Package p ...\n//\n// @ai:generated by=x date=2026-01-01\npackage p\n\n// @ai:generated by=x date=2026-01-01\nfunc CreateUser() {\n\tprintln()\n}\n")

	_ = runChkCommentCmd(t, "--fixintent", "x.go")

	out, _ := os.ReadFile("x.go")
	if !strings.Contains(string(out), "//@ai:think intent=建立資源 model=heuristic") {
		t.Errorf("heuristic @ai:think not inserted:\n%s", out)
	}
}

// TestChkCommentHonorsCommentYAML 迴歸測試（D1）：依 .hyp/comment.yaml 決定違規標準，comment.yaml 由檔案位置往上找。
// 歷史 bug：完全忽略 comment.yaml，預設（ai_comment=false）下仍要求並插入 @ai 骨架。
func TestChkCommentHonorsCommentYAML(t *testing.T) {
	// 無 comment.yaml → 預設只要求普通 doc：有 doc 即通過，--fix 不插 @ai
	dir := t.TempDir()
	t.Chdir(dir)
	writeChkFile(t, "x.go", "package p\n\n// F does f.\nfunc F() {}\n")
	if err := runChkCommentCmd(t, "--fix", "x.go"); err != nil {
		t.Errorf("doc present + ai_comment=false should pass, got %v", err)
	}
	if out, _ := os.ReadFile("x.go"); strings.Contains(string(out), "@ai:") {
		t.Errorf("--fix inserted @ai although ai_comment=false:\n%s", out)
	}
	writeChkFile(t, "y.go", "package p\n\nfunc G() {}\n")
	if err := runChkCommentCmd(t, "y.go"); err == nil {
		t.Error("missing doc should still be a violation under normal_comment=true")
	}

	// comment.yaml 位於上層專案根目錄、CWD 在別處 → 仍套用 ai_comment=true
	proj := t.TempDir()
	writeChkFile(t, filepath.Join(proj, ".hyp", "comment.yaml"), commentYAMLAllOn)
	file := filepath.Join(proj, "sub", "x.go")
	writeChkFile(t, file, "package p\n\n// F does f.\nfunc F() {}\n")
	t.Chdir(t.TempDir())
	if err := runChkCommentCmd(t, file); err == nil {
		t.Error("ai_comment=true from the project's comment.yaml should require @ai fields")
	}
}

// TestChkCommentAcceptsDirectories 迴歸測試（D2）：接受目錄與 ./...，跳過 vendor/、testdata/、隱藏目錄與 _test.go。
// 歷史 bug：只接受單一 .go 檔，`hyp chkcomment ./...`（CLAUDE.md 的範例）直接報錯。
func TestChkCommentAcceptsDirectories(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	writeChkFile(t, "sub/a.go", "package sub\n\n// F does f.\nfunc F() {}\n")
	bad := "package x\n\nfunc V() {}\n"
	writeChkFile(t, "vendor/v.go", bad)
	writeChkFile(t, "testdata/t.go", bad)
	writeChkFile(t, ".hidden/h.go", bad)
	writeChkFile(t, "sub/a_test.go", bad)

	if err := runChkCommentCmd(t, "./..."); err != nil {
		t.Errorf("./... should pass (violations only in skipped paths), got %v", err)
	}
	writeChkFile(t, "sub/deep/b.go", bad)
	if err := runChkCommentCmd(t, "./..."); err == nil {
		t.Error("violation in sub/deep/b.go should fail ./...")
	}
	if err := runChkCommentCmd(t, "sub"); err != nil {
		t.Errorf("plain dir is non-recursive and sub/ itself is clean, got %v", err)
	}
}
